/// The exports that cross the binary wire, with their Java body and Rust code.
fn java_wire_fns<'m>(
    m: &'m Manifest,
    api: &crate::codegen::PortApi,
) -> Vec<(&'m crate::ts::exports::ExportedFn, String, String)> {
    let class = java_native_class(m);
    let mut out = Vec::new();
    for f in &api.functions {
        if typed(m, f).is_some() {
            continue;
        }
        let Some(e) = m.exports.iter().find(|e| e.name == f.js_name) else {
            continue;
        };
        if e.params.len() != f.params.len() {
            continue;
        }
        let Some(params) = e
            .params
            .iter()
            .map(|p| Some((p.name.clone(), java_ty(p.native_type.as_deref()?)?)))
            .collect::<Option<Vec<_>>>()
        else {
            continue;
        };
        let ret_java = e.native_return.as_deref().unwrap_or("void");
        let result = if ret_java == "void" {
            None
        } else {
            java_ty(ret_java)
        };
        if ret_java != "void" && result.is_none() {
            continue;
        }
        // Java body of `call_<name>`.
        let mut java =
            String::from("        RustAnythingWire.Writer w = new RustAnythingWire.Writer();\n");
        for (name, t) in &params {
            let _ = writeln!(java, "        {}", java_enc(name, t, 0));
        }
        let _ = writeln!(
            java,
            "        String[] slot = RustAnythingError.slot();\n        byte[] out = w_{}(w.bytes(), slot);\n        RustAnythingError.check(slot);",
            f.js_name
        );
        if let Some(t) = &result {
            let Some(dec) = java_dec(t) else { continue };
            let _ = writeln!(
                java,
                "        RustAnythingWire.Reader r = new RustAnythingWire.Reader(out);\n        return {dec};"
            );
        }
        // Rust JNI function.
        let mut statics = String::new();
        let prefix = format!("S_{}", f.js_name.to_uppercase());
        let Some(reads) = crate::wire::rust_read_args(&params, &f.params, &prefix, &mut statics)
        else {
            continue;
        };
        let args: Vec<&str> = f.params.iter().map(|(n, _)| n.as_str()).collect();
        let call = format!("port::{}({})", f.rust_name, args.join(", "));
        let call = if f.fallible { format!("{call}?") } else { call };
        let write = match &result {
            None if f.ret == "()" => format!("        let () = {call};\n"),
            None => continue,
            Some(t) => {
                let schema = format!("{prefix}_OUT");
                let Some(w) = crate::wire::rust_write(t, &f.ret, "out", &schema, 0) else {
                    continue;
                };
                if w.contains(&schema) {
                    let _ = writeln!(
                        statics,
                        "static {schema}: wire::Schema = {};",
                        crate::wire::schema_expr(t)
                    );
                }
                format!("        let out = &{call};\n        {w}\n")
            }
        };
        let rust = format!(
            "\n{statics}\n/// `{proto}`: binary wire.\n// SAFETY: the JNI symbol of `rustanything.{class}.w_{js}`; nothing else defines it.\n\
             #[unsafe(no_mangle)]\npub extern \"system\" fn Java_rustanything_{mclass}_w_1{mjs}<'local>(mut env: jni::JNIEnv<'local>, \
             _class: jni::objects::JClass<'local>, args: jni::objects::JByteArray<'local>, slot: jni::objects::JObjectArray<'local>) -> jni::sys::jbyteArray {{\n    \
             let Ok(input) = env.convert_byte_array(&args) else {{\n        return std::ptr::null_mut();\n    }};\n    \
             let result = run(|| {{\n        let r = &mut wire::Reader::new(&input);\n{reads}        let w = &mut wire::Writer::default();\n{write}        \
             Ok(std::mem::take(&mut w.0))\n    }});\n    match result {{\n        \
             Ok(bytes) => env.byte_array_from_slice(&bytes).map_or(std::ptr::null_mut(), jni::objects::JByteArray::into_raw),\n        \
             Err(message) => {{\n            report(&mut env, &slot, &message);\n            std::ptr::null_mut()\n        }}\n    }}\n}}",
            proto = e.prototype.as_deref().unwrap_or(&e.name),
            js = f.js_name,
            mclass = mangle_jni_component(&class),
            mjs = mangle_jni_component(&f.js_name),
        );
        out.push((e, java, rust));
    }
    out
}

/// Rust code of every wire export, for `lib.rs`.
pub fn wire_rs(m: &Manifest, api: &crate::codegen::PortApi) -> String {
    java_wire_fns(m, api)
        .into_iter()
        .map(|(_, _, rust)| rust)
        .collect()
}

/// `call_<name>` methods of the native class: the one entry point wrappers and shadows use.
fn call_methods(m: &Manifest, api: &crate::codegen::PortApi) -> String {
    let mut out = String::new();
    let sig = |e: &crate::ts::exports::ExportedFn| {
        e.params
            .iter()
            .map(|p| {
                format!(
                    "{} {}",
                    p.native_type.as_deref().unwrap_or("Object"),
                    p.name
                )
            })
            .collect::<Vec<_>>()
            .join(", ")
    };
    for f in &api.functions {
        let Some(e) = typed(m, f) else { continue };
        let ret = e.native_return.as_deref().unwrap_or("void");
        let args = e
            .params
            .iter()
            .map(|p| p.name.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        let call_args = if args.is_empty() {
            "slot".to_string()
        } else {
            format!("{args}, slot")
        };
        let body = if ret == "void" {
            format!(
                "String[] slot = RustAnythingError.slot();\n            n_{}({call_args});\n            RustAnythingError.check(slot);",
                f.js_name
            )
        } else {
            format!(
                "String[] slot = RustAnythingError.slot();\n            {ret} out = n_{}({call_args});\n            RustAnythingError.check(slot);\n            return out;",
                f.js_name
            )
        };
        let _ = writeln!(
            out,
            "\n    public static {ret} call_{}({}) {{\n        try {{\n            {body}\n        }} catch (RustAnythingError e) {{\n            throw e.real();\n        }}\n    }}",
            f.js_name,
            sig(e)
        );
    }
    for (e, body, _) in java_wire_fns(m, api) {
        let ret = e.native_return.as_deref().unwrap_or("void");
        let _ = writeln!(
            out,
            "\n    private static native byte[] w_{name}(byte[] args, String[] slot);\n\n    @SuppressWarnings(\"unchecked\")\n    public static {ret} call_{name}({}) {{\n        try {{\n{body}        }} catch (RustAnythingError e) {{\n            throw e.real();\n        }}\n    }}",
            sig(e),
            name = e.name,
        );
    }
    out
}

/// The exports with a `call_<name>` method (typed or wire).
fn direct_names(m: &Manifest, api: &crate::codegen::PortApi) -> Vec<String> {
    let mut names = typed_names(m, api);
    names.extend(
        java_wire_fns(m, api)
            .into_iter()
            .map(|(e, ..)| e.name.clone()),
    );
    names
}

