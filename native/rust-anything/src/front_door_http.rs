const SHUTDOWN: &str = "
/// Ctrl-C or SIGTERM: stop taking requests and finish the open ones.
pub async fn shutdown_signal() {
    #[cfg(unix)]
    {
        let mut term =
            tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())
                .expect(\"a SIGTERM handler\");
        tokio::select! {
            _ = tokio::signal::ctrl_c() => {}
            _ = term.recv() => {}
        }
    }
    #[cfg(not(unix))]
    {
        let _ = tokio::signal::ctrl_c().await;
    }
}
";

fn serve(app: &str) -> String {
    format!(
        "    let port = std::env::var(\"PORT\")
        .ok()
        .and_then(|p| p.parse().ok())
        .unwrap_or(8080);
    let listener = tokio::net::TcpListener::bind(SocketAddr::from(([0, 0, 0, 0], port)))
        .await
        .expect(\"binding the port\");
    let listener = listener.tap_io(|tcp| {{
        let _ = tcp.set_nodelay(true);
    }});
    axum::serve(listener, {app})
        .with_graceful_shutdown(shutdown_signal())
        .await
        .expect(\"serving\");
"
    )
}

pub(crate) fn main_rs() -> String {
    format!(
        "mod original;
mod units;

use std::net::SocketAddr;

use axum::serve::ListenerExt;
use original::shutdown_signal;

#[tokio::main]
async fn main() {{
    original::report_fallbacks();
    let original = original::Original::start().await;
    let app = units::router().with_state(original.clone());
{}    original.stop();
}}
",
        serve("app")
    )
}

/// `main.rs` of the front door as this version writes it, then as earlier versions did (before
/// `TCP_NODELAY`): lift recognizes either as untouched.
pub(crate) fn main_rs_versions() -> Vec<String> {
    let current = main_rs();
    let before_nodelay = current
        .replace(
            "    let listener = listener.tap_io(|tcp| {\n        let _ = tcp.set_nodelay(true);\n    });\n",
            "",
        )
        .replace("use axum::serve::ListenerExt;\n", "");
    vec![current, before_nodelay]
}

pub(crate) fn lifted_main_rs() -> String {
    format!(
        "mod units;

use std::net::SocketAddr;

use axum::serve::ListenerExt;

#[tokio::main]
async fn main() {{
{}}}
{SHUTDOWN}",
        serve("units::router()")
    )
}

/// `in_root`: the original runs in the repository, as recorded; otherwise in the front door's
/// own working directory (the recording copies fresh files there).
pub(crate) fn original_rs(run: &[String], in_root: bool) -> String {
    let words: Vec<String> = run.iter().map(|w| format!("{w:?}")).collect();
    let cwd = if in_root {
        ".current_dir(ROOT)
            "
    } else {
        ""
    };
    format!(
        "use std::ffi::OsString;
use std::io::Write;
use std::net::TcpListener;
use std::path::Path;
use std::process::{{Child, Command, Stdio}};
use std::sync::{{Arc, Mutex}};
use std::time::{{Duration, Instant}};

use axum::body::Body;
use axum::extract::{{Request, State}};
use axum::http::{{StatusCode, header}};
use axum::response::{{IntoResponse, Response}};

const ROOT: &str = match option_env!(\"RUST_ANYTHING_REPO\") {{
    Some(root) => root,
    None => concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/../..\"),
}};
const RUN: &[&str] = &[{words}];
const FALLBACK_LOG: &str = \"{log}\";

fn resolve(word: &str, port: u16) -> OsString {{
    let word = word.replace(\"{{port}}\", &port.to_string());
    if word.starts_with('-') {{
        return word.into();
    }}
    let path = Path::new(ROOT).join(&word);
    let looks_like_path = word.contains('/') || word.contains('\\\\') || path.is_file();
    if looks_like_path && path.exists() {{
        return std::path::absolute(&path).unwrap_or(path).into_os_string();
    }}
    word.into()
}}

fn log() -> Option<std::fs::File> {{
    let path = std::env::var_os(FALLBACK_LOG)?;
    std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(path)
        .ok()
}}

/// Tells `rust-anything app replay` this build counts its fallbacks, even when it makes none.
pub fn report_fallbacks() {{
    let _ = log();
}}

/// The original server, started on a free port of its own.
#[derive(Clone)]
pub struct Original {{
    base: String,
    client: reqwest::Client,
    child: Arc<Mutex<Option<Child>>>,
}}

impl Original {{
    pub async fn start() -> Self {{
        let port = TcpListener::bind(\"127.0.0.1:0\")
            .and_then(|l| l.local_addr())
            .map(|a| a.port())
            .expect(\"a free port\");
        let (program, rest) = RUN.split_first().expect(\"the original's command\");
        let mut child = Command::new(resolve(program, port))
            .args(rest.iter().map(|w| resolve(w, port)))
            .args(std::env::args_os().skip(1))
            {cwd}.env(\"PORT\", port.to_string())
            .env_remove(FALLBACK_LOG)
            .stdin(Stdio::null())
            .spawn()
            .expect(\"starting the original\");
        let deadline = Instant::now() + Duration::from_secs(60);
        while tokio::net::TcpStream::connect((\"127.0.0.1\", port))
            .await
            .is_err()
        {{
            if let Ok(Some(status)) = child.try_wait() {{
                panic!(\"the original exited ({{status}}) before listening on port {{port}}\");
            }}
            assert!(
                Instant::now() < deadline,
                \"the original did not listen on port {{port}}\"
            );
            tokio::time::sleep(Duration::from_millis(50)).await;
        }}
        let client = reqwest::Client::builder()
            .no_proxy()
            .redirect(reqwest::redirect::Policy::none())
            .build()
            .expect(\"an HTTP client\");
        Original {{
            base: format!(\"http://127.0.0.1:{{port}}\"),
            client,
            child: Arc::new(Mutex::new(Some(child))),
        }}
    }}

    pub fn stop(&self) {{
        if let Ok(mut slot) = self.child.lock()
            && let Some(mut child) = slot.take()
        {{
            let _ = child.kill();
            let _ = child.wait();
        }}
    }}
}}

/// Sends the request to the original and passes its answer through. Each call is one fallback.
pub async fn proxy(State(original): State<Original>, req: Request) -> Response {{
    let (parts, body) = req.into_parts();
    let target = parts
        .uri
        .path_and_query()
        .map_or(\"/\", |p| p.as_str())
        .to_string();
    if let Some(mut file) = log() {{
        let _ = writeln!(file, \"{{}} {{target}}\", parts.method);
    }}
    let Ok(body) = axum::body::to_bytes(body, usize::MAX).await else {{
        return (StatusCode::BAD_REQUEST, \"front door: unreadable request body\").into_response();
    }};
    let mut request = original
        .client
        .request(parts.method, format!(\"{{}}{{target}}\", original.base))
        .body(body);
    for (name, value) in &parts.headers {{
        if name != header::HOST {{
            request = request.header(name, value);
        }}
    }}
    match request.send().await {{
        Ok(answer) => {{
            let mut response = Response::builder().status(answer.status());
            for (name, value) in answer.headers() {{
                if name != header::TRANSFER_ENCODING && name != header::CONNECTION {{
                    response = response.header(name, value);
                }}
            }}
            let body = answer.bytes().await.unwrap_or_default();
            response
                .body(Body::from(body))
                .unwrap_or_else(|_| StatusCode::BAD_GATEWAY.into_response())
        }}
        Err(e) => (
            StatusCode::BAD_GATEWAY,
            format!(\"front door: the original did not answer: {{e}}\"),
        )
            .into_response(),
    }}
}}
{SHUTDOWN}",
        words = words.join(", "),
        log = app::FALLBACK_ENV
    )
}

/// Path parameters are read from the URI here rather than by axum's extractors, which answer a
/// 400 of their own when an escape is not UTF-8: the unit gets every request, as the original does.
const PATH_PARAMS: &str = "
/// The parameters of `route` (`/users/{id}`, `/files/{*rest}`) in `path`, percent-decoded; one
/// whose escapes are not UTF-8 stays as sent.
fn path_params(route: &str, path: &str) -> HashMap<String, String> {
    let mut out = HashMap::new();
    let mut segments = path.trim_start_matches('/').split('/');
    for part in route.trim_start_matches('/').split('/') {
        if let Some(name) = part.strip_prefix(\"{*\").and_then(|p| p.strip_suffix('}')) {
            let rest: Vec<&str> = segments.by_ref().collect();
            out.insert(name.to_string(), decode(&rest.join(\"/\")));
            break;
        }
        let segment = segments.next().unwrap_or_default();
        if let Some(name) = part.strip_prefix('{').and_then(|p| p.strip_suffix('}')) {
            out.insert(name.to_string(), decode(segment));
        }
    }
    out
}

fn decode(text: &str) -> String {
    let bytes = text.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        let hex = |at: usize| bytes.get(at).and_then(|b| char::from(*b).to_digit(16));
        if bytes[i] == b'%'
            && let (Some(high), Some(low)) = (hex(i + 1), hex(i + 2))
        {
            out.push((high * 16 + low) as u8);
            i += 3;
        } else {
            out.push(bytes[i]);
            i += 1;
        }
    }
    String::from_utf8(out).unwrap_or_else(|_| text.to_string())
}
";

fn method_fn(method: &Option<String>) -> String {
    method
        .as_deref()
        .map_or("any".to_string(), str::to_ascii_lowercase)
}

/// `src/units/mod.rs`: wired routes in front of the original (front door), or alone (lifted).
pub(crate) fn units_rs(state: &State, lifted: bool) -> String {
    let mut handlers: Vec<(String, Route, String)> = Vec::new();
    for unit in &state.units {
        for text in &unit.routes {
            if let Ok(route) = Route::parse(text) {
                handlers.push((ident(&unit.name), route, unit.switch.clone()));
            }
        }
    }
    let header = if lifted {
        "//! Written by `rust-anything app lift`: every route is answered in Rust.\n\n"
    } else {
        "//! Generated by `rust-anything app wire` from rust-anything.json; it is rewritten on every wire.\n\n"
    };
    let mut out = header.to_string();
    if handlers.is_empty() && !lifted {
        out += "use axum::Router;\n\nuse crate::original::{self, Original};\n\n\
                pub fn router() -> Router<Original> {\n    Router::new().fallback(original::proxy)\n}\n";
        return out;
    }
    let state_ty = if lifted { "" } else { "<Original>" };
    let mut methods: Vec<String> = handlers
        .iter()
        .filter(|(_, r, _)| r.path != "*")
        .map(|(_, r, _)| method_fn(&r.method))
        .collect();
    methods.sort();
    methods.dedup();
    let any_params = handlers.iter().any(|(_, r, _)| r.has_params());
    out += "use std::collections::HashMap;\n\nuse axum::Router;\n";
    out += &format!(
        "use axum::extract::{{{}Request{}}};\n",
        "",
        if lifted { "" } else { ", State" }
    );
    out += "use axum::response::Response;\n";
    if !methods.is_empty() {
        out += &format!("use axum::routing::{{{}}};\n", methods.join(", "));
    }
    if !lifted {
        out += "\nuse crate::original::{self, Original};\n";
    }
    out.push('\n');
    let mut modules: Vec<&String> = handlers.iter().map(|(m, _, _)| m).collect();
    modules.sort();
    modules.dedup();
    for module in modules {
        out += &format!("mod {module};\n");
    }
    if !lifted {
        out += &format!(
            "\n/// `{KILL_SWITCH_PREFIX}<NAME>=original` sends that unit back to the original.\n\
             fn sent_to_original(unit: &str) -> bool {{\n    \
                 std::env::var(format!(\"{KILL_SWITCH_PREFIX}{{unit}}\")).is_ok_and(|v| v == \"original\")\n\
             }}\n"
        );
    }
    if any_params {
        out += PATH_PARAMS;
    }
    let star = handlers.iter().position(|(_, r, _)| r.path == "*");
    let fallback = match (star, lifted) {
        (Some(_), _) => Some("fallback"),
        (None, false) => Some("original::proxy"),
        (None, true) => None,
    };
    let mut by_path: BTreeMap<&str, Vec<(usize, &Route)>> = BTreeMap::new();
    for (i, (_, route, _)) in handlers.iter().enumerate() {
        if route.path != "*" {
            by_path
                .entry(route.path.as_str())
                .or_default()
                .push((i, route));
        }
    }
    out += &format!("\npub fn router() -> Router{state_ty} {{\n    Router::new()\n");
    for (path, routes) in &by_path {
        let mut chain: Vec<String> = routes
            .iter()
            .map(|(i, r)| format!("{}(route_{i})", method_fn(&r.method)))
            .collect();
        let any_method = routes.iter().any(|(_, r)| r.method.is_none());
        let mut line = chain.remove(0);
        for c in chain {
            line += &format!(".{c}");
        }
        if !any_method && let Some(f) = fallback {
            line += &format!(".fallback({f})");
        }
        out += &format!("        .route({path:?}, {line})\n");
    }
    if let Some(f) = fallback {
        out += &format!("        .fallback({f})\n");
    }
    out += "}\n";
    for (i, (module, route, switch)) in handlers.iter().enumerate() {
        let name = if route.path == "*" {
            "fallback".to_string()
        } else {
            format!("route_{i}")
        };
        let mut params = Vec::new();
        if !lifted {
            params.push("State(original): State<Original>".to_string());
        }
        params.push("req: Request".to_string());
        out += &format!("\nasync fn {name}({}) -> Response {{\n", params.join(", "));
        if !lifted {
            let switch = switch.strip_prefix(KILL_SWITCH_PREFIX).unwrap_or(switch);
            out += &format!(
                "    if sent_to_original({switch:?}) {{\n        return original::proxy(State(original), req).await;\n    }}\n"
            );
        }
        out += &format!(
            "    {module}::handle({:?}, {}, req).await\n}}\n",
            route.key(),
            if route.has_params() {
                format!("path_params({:?}, req.uri().path())", route.path)
            } else {
                "HashMap::new()".to_string()
            }
        );
    }
    out
}

pub(crate) fn glue_rs(crate_name: &str) -> String {
    let krate = crate_name.replace('-', "_");
    format!(
        "//! Glue from the front door to `{crate_name}`: read the request, call `{krate}::port`,\n\
         //! answer what the original answers (status, headers that matter, body).\n\n\
         use std::collections::HashMap;\n\n\
         use axum::extract::Request;\n\
         use axum::response::Response;\n\n\
         /// `route` is the route as wired (`GET /users/{{id}}`, or `*`), `params` its path parameters.\n\
         pub async fn handle(route: &str, params: HashMap<String, String>, req: Request) -> Response {{\n    \
             unimplemented!(\"glue for `{{route}}` {{params:?}} {{}}: call {krate}::port\", req.uri())\n\
         }}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::front_door::{AppKind, WiredUnit};

    fn state(routes: &[&str]) -> State {
        State {
            schema: String::new(),
            name: "srv".into(),
            commands: Vec::new(),
            units: vec![WiredUnit {
                name: "api".into(),
                crate_name: "api-rs".into(),
                path: "../api-rs".into(),
                commands: Vec::new(),
                routes: routes.iter().map(|r| r.to_string()).collect(),
                switch: "RUST_ANYTHING_UNIT_API".into(),
                unit: None,
                shadow: None,
                kept: Vec::new(),
            }],
            lifted: false,
            kind: AppKind::Http,
            routes: Vec::new(),
            api: Vec::new(),
        }
    }

    #[test]
    fn generated_servers_send_without_nagle_delays() {
        for code in [main_rs(), lifted_main_rs()] {
            assert!(code.contains("tcp.set_nodelay(true)"), "{code}");
            assert!(code.contains("use axum::serve::ListenerExt;"), "{code}");
        }
        let versions = main_rs_versions();
        assert!(!versions[1].contains("nodelay") && !versions[1].contains("ListenerExt"));
    }

    #[test]
    fn routes_parse_and_overlaps_are_refused() {
        assert_eq!(
            Route::parse("get /div/{a}/{b}").unwrap().key(),
            "GET /div/{a}/{b}"
        );
        assert_eq!(Route::parse("/any").unwrap().method, None);
        assert!(Route::parse("FETCH /x").is_err());
        assert!(Route::parse("GET x").is_err());
        let s = state(&["GET /hello", "*"]);
        assert!(check_routes(&s, "other", &["POST /hello".into()]).is_ok());
        assert!(check_routes(&s, "other", &["GET /hello".into()]).is_err());
        assert!(check_routes(&s, "other", &["/hello".into()]).is_err());
        assert!(check_routes(&s, "other", &["*".into()]).is_err());
        assert!(check_routes(&s, "api", &["GET /hello".into()]).is_ok());
    }

    #[test]
    fn units_route_with_kill_switches_and_fallback() {
        let s = state(&["GET /div/{a}/{b}", "POST /div/{a}/{b}", "GET /hello", "*"]);
        let code = units_rs(&s, false);
        assert!(
            code.contains(
                ".route(\"/div/{a}/{b}\", get(route_0).post(route_1).fallback(fallback))"
            ),
            "{code}"
        );
        assert!(code.contains("if sent_to_original(\"API\")"), "{code}");
        assert!(
            code.contains("api::handle(\"*\", HashMap::new(), req).await"),
            "{code}"
        );
        assert!(
            code.contains("api::handle(\"GET /div/{a}/{b}\", path_params(\"/div/{a}/{b}\", req.uri().path()), req)"),
            "{code}"
        );
        let lifted = units_rs(&s, true);
        assert!(!lifted.contains("original"), "{lifted}");
        assert!(lifted.contains("pub fn router() -> Router {"), "{lifted}");
        let empty = units_rs(&state(&[]), false);
        assert!(empty.contains("Router::new().fallback(original::proxy)"));
        let no_star = units_rs(&state(&["GET /hello"]), true);
        assert!(!no_star.contains(".fallback("), "{no_star}");
    }
}
